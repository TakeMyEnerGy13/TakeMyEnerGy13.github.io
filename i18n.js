const originals = new WeakMap();
const attributes = new WeakMap();
let language = 'ru';
try { if (localStorage.getItem('portfolio-language') === 'en') language = 'en'; } catch {}
export function translate(root = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest('script,style')) continue;
    if (!originals.has(node)) originals.set(node, node.textContent);
    const original = originals.get(node), key = original.trim();
    if (translations[key]) node.textContent = language === 'en' ? original.replace(key, translations[key]) : original;
  }
  for (const element of root.querySelectorAll('[aria-label],[alt],meta[content]')) {
    if (!attributes.has(element)) attributes.set(element, {});
    const saved = attributes.get(element);
    for (const name of ['aria-label', 'alt', 'content']) {
      if (!element.hasAttribute(name)) continue;
      if (!(name in saved)) saved[name] = element.getAttribute(name);
      if (translations[saved[name]]) element.setAttribute(name, language === 'en' ? translations[saved[name]] : saved[name]);
    }
  }
}
function applyLanguage() {
  document.documentElement.lang = language;
  translate();
  document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
  document.dispatchEvent(new Event('languagechange'));
}
export function initializeLanguage() {
  document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => {
    language = button.dataset.language;
    try { localStorage.setItem('portfolio-language', language); } catch {}
    applyLanguage();
  }));
  applyLanguage();
}
